// =============================================================================
//  cfp/types.hpp — 파이프라인 전 구간에서 공유하는 값 타입
//
//  [설계 의도] 이 헤더는 의도적으로 OpenCV에 의존하지 않는다.
//  미뉴셔·템플릿·평가 지표는 "영상"이 아니라 "숫자"만 다루므로,
//  OpenCV 없이 컴파일·단위테스트가 가능해야 CI가 가벼워지고
//  매칭/평가 로직을 영상 스택과 독립적으로 검증할 수 있다.
//  영상을 다루는 타입(cv::Mat)은 abstractions.hpp 이하에만 등장한다.
// =============================================================================
#pragma once

#include <cstdint>
#include <string>
#include <vector>

namespace cfp {

// -----------------------------------------------------------------------------
// 미뉴셔 종류. research.md §4.3 / ISO/IEC 19794-2의 최소 집합.
// -----------------------------------------------------------------------------
enum class MinutiaType : std::uint8_t {
    Unknown     = 0,
    RidgeEnding = 1,   // 융선 끝점      (Crossing Number == 1)
    Bifurcation = 2,   // 융선 분기점    (Crossing Number == 3)
};

// -----------------------------------------------------------------------------
// 단일 미뉴셔.
//  theta: 융선이 뻗어나가는 방향. [0, 2pi) 라디안.
//         주의 — 융선 "방향장(orientation)"은 pi 주기(방향성 없음)지만,
//         미뉴셔 "방향(direction)"은 2pi 주기(방향성 있음)다.
//         이 둘을 섞으면 매칭이 조용히 망가진다.
// -----------------------------------------------------------------------------
struct Minutia {
    float       x       = 0.0f;   // px, 영상 좌표계
    float       y       = 0.0f;
    float       theta   = 0.0f;   // rad, [0, 2pi)
    float       quality = 0.0f;   // 0..1, 국소 융선 선명도
    MinutiaType type    = MinutiaType::Unknown;
};

// -----------------------------------------------------------------------------
// 등록/검증에 저장되는 템플릿. 원본 영상은 담지 않는다(§8 프라이버시 원칙).
// -----------------------------------------------------------------------------
struct Template {
    std::string          subject_id;      // 피험자 식별자
    std::string          capture_id;      // 촬영 회차
    int                  width  = 0;      // 미뉴셔 좌표가 정의된 ROI 크기
    int                  height = 0;
    std::vector<Minutia> minutiae;

    bool empty() const noexcept { return minutiae.empty(); }
};

// -----------------------------------------------------------------------------
// 품질 게이트 결과 (dev_plan V2).
// -----------------------------------------------------------------------------
struct QualityReport {
    double      sharpness  = 0.0;   // Laplacian 분산 — 초점
    double      brightness = 0.0;   // 평균 밝기 0..255
    double      contrast   = 0.0;   // 표준편차
    double      clipping   = 0.0;   // 0 또는 255로 포화된 픽셀 비율 0..1
    bool        pass       = false;
    std::string reason;             // 실패 사유(UI 툴팁용)
};

// -----------------------------------------------------------------------------
// 파이프라인 단계별 소요 시간(ms). HUD/프로파일링용.
// -----------------------------------------------------------------------------
struct StageTiming {
    std::string stage;
    double      ms = 0.0;
};

}  // namespace cfp
